//! Typed game events. This module is the single source of the event schema;
//! the TypeScript SDK types are generated from it: see
//! `sdk/src/generated/events.ts` and the test that keeps it current.

use serde::Serialize;
use ts_rs::TS;

/// Version of the event schema. Bump on any change plugins can observe.
/// 2: `ExpChanged` gained `needed`, and its `level` became optional.
/// 3: `MesosGained`, `ItemGained` and `NoticesMissed`, from the pickup notices.
pub const SCHEMA_VERSION: u32 = 3;

/// Events the engine emits after a confident read (below the confidence
/// threshold a recognizer reports "unreadable" and no value event is sent).
///
/// As JSON, an event is an object whose `type` names the variant, with its fields beside it.
#[derive(Debug, Clone, PartialEq, Serialize, TS)]
#[serde(tag = "type")]
pub enum Event {
    /// The EXP bar was read: the level (when known), EXP into the level, the
    /// percentage shown on the bar (hundredths of a percent, 6420 = 64.20%), and
    /// the EXP the whole level needs (when known).
    ExpChanged {
        level: Option<u16>,
        #[ts(type = "number")]
        exp: u64,
        pct_hundredths: u16,
        #[ts(type = "number | null")]
        needed: Option<u64>,
    },
    /// The level went up by one or more.
    LevelUp { level: u16 },
    /// Mesos picked up: the game's "You have gained mesos (+N)".
    MesosGained {
        #[ts(type = "number")]
        amount: u64,
    },
    /// An item picked up: the game's "<name> xN earned. (<tab>)". `item` is the name's exact
    /// shape as text, the same every time the same item is picked up, whether or not its letters
    /// are known yet. `tab` is the inventory tab it went to ("Equip", "Use", "Setup", "Etc" or
    /// "Cash"), when its letters are known.
    ItemGained {
        item: String,
        count: u32,
        tab: Option<&'static str>,
    },
    /// Pickup notices may have been missed, so the mesos and items counted from them are at
    /// least what was picked up. `reason`: `unaligned` (the notices moved in a way that lines up
    /// with nothing, as when something covered them), `unreadable` (a new line couldn't be read),
    /// `not_learned` (a mesos amount has a digit not learned yet), `exp_short` or `exp_over` (the
    /// EXP lines read don't add up to what the EXP bar gained), `lost` (the notices were out of
    /// sight for a while).
    NoticesMissed { reason: &'static str },
    /// A recognizer could not read its region confidently.
    Unreadable { recognizer: &'static str },
}

#[cfg(test)]
mod tests {
    use super::*;

    /// Where the SDK's generated event types live.
    const SDK_EVENTS: &str = concat!(
        env!("CARGO_MANIFEST_DIR"),
        "/../sdk/src/generated/events.ts"
    );

    fn generated() -> String {
        let body = Event::export_to_string(&ts_rs::Config::new()).expect("Event exports");
        // ts-rs starts with its own banner; keep only the declarations.
        let body = body
            .lines()
            .filter(|line| !line.starts_with("// This file was generated by"))
            .collect::<Vec<_>>()
            .join("\n");
        format!(
            "// Generated from engine/src/events.rs by its tests. Don't edit: change the Rust and run\n\
             // `MESOVIBE_UPDATE_SDK=1 cargo test -p mesovibe-engine events`.\n\n\
             /** The event schema version these types describe. */\n\
             export const SCHEMA_VERSION = {SCHEMA_VERSION};\n\n{}\n",
            body.trim()
        )
    }

    // Plugins see exactly the events the engine emits. Fails when an Event variant or field
    // changes and the SDK types weren't regenerated.
    #[test]
    fn the_sdk_event_types_match_the_engine() {
        let want = generated();
        if std::env::var_os("MESOVIBE_UPDATE_SDK").is_some() {
            std::fs::write(SDK_EVENTS, &want).expect("write the SDK's event types");
        }
        // Git on Windows may check the file out with CRLF line endings; only the content counts.
        let have = std::fs::read_to_string(SDK_EVENTS)
            .unwrap_or_default()
            .replace("\r\n", "\n");
        assert!(
            have == want,
            "sdk/src/generated/events.ts is stale. Run \
             `MESOVIBE_UPDATE_SDK=1 cargo test -p mesovibe-engine events` and commit it."
        );
    }

    #[test]
    fn events_are_tagged_json() {
        let event = Event::ExpChanged {
            level: Some(42),
            exp: 230_622,
            pct_hundredths: 6462,
            needed: Some(356_916),
        };
        let json = serde_json::to_string(&event).unwrap();
        assert_eq!(
            json,
            r#"{"type":"ExpChanged","level":42,"exp":230622,"pct_hundredths":6462,"needed":356916}"#
        );
    }
}
